import { renderEmailLayout, renderCallout, escapeHtml } from '../email.renderer';
import { EMAIL_LINKS } from '../email.constants';
import { RenderedEmail } from '../email.types';

export function buildTicketUpdateEmail(
  to: string,
  ticketSubject: string,
  replyMessage: string,
  ticketId?: string
): RenderedEmail {
  const greeting = 'Hello,';
  const title = 'New Support Ticket Reply 💬';
  const preheader = `A response has been added to ticket: ${ticketSubject}`;

  const contentHtml = `
    <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%">
      <tr>
        <td style="font-family: 'Google Sans', 'Plus Jakarta Sans', Arial, sans-serif; font-size: 15.5px; line-height: 25px; color: #4F5A68;">
          Our support team has posted a reply on your inquiry: <strong>"${escapeHtml(ticketSubject)}"</strong>
        </td>
      </tr>
    </table>

    <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%" style="background: #F8FAFF; border-left: 4px solid #6336EB; border-radius: 0 12px 12px 0; margin: 20px 0; padding: 18px 20px;">
      <tr>
        <td>
          <div style="font-family: 'Google Sans', 'Plus Jakarta Sans', Arial, sans-serif; font-size: 12.5px; font-weight: 700; color: #4338CA; text-transform: uppercase; letter-spacing: 0.5px; margin-bottom: 8px;">
            Support Team Message ${ticketId ? `(#${ticketId})` : ''}
          </div>
          <div style="font-family: 'Google Sans', 'Plus Jakarta Sans', Arial, sans-serif; font-size: 15px; line-height: 23px; color: #1E1B4B; white-space: pre-line;">
            ${escapeHtml(replyMessage)}
          </div>
        </td>
      </tr>
    </table>

    ${renderCallout('You can reply to this thread directly in the Knotnex Help Center or respond to this email.', 'info')}
  `;

  return renderEmailLayout({
    preheader,
    greeting,
    title,
    badge: {
      text: 'Support Ticket',
      bg: '#EEF2FF',
      color: '#4338CA',
    },
    contentHtml,
    cta: {
      text: 'View Ticket Thread',
      url: EMAIL_LINKS.SUPPORT,
    },
    secondaryNotice: 'Knotnex accessibility and technical assistance operates 24/7.',
  });
}

export function buildAdminQuotaAlertEmail(currentCount: number, maxQuota: number = 300): RenderedEmail {
  const greeting = 'Dear Knotnex Administrator,';
  const title = '⚠️ Daily Brevo Email Quota Alert';
  const preheader = `Brevo daily email quota reached ${currentCount}/${maxQuota} (${Math.round((currentCount / maxQuota) * 100)}%).`;
  const pct = Math.round((currentCount / maxQuota) * 100);
  const remaining = Math.max(0, maxQuota - currentCount);

  const contentHtml = `
    <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%">
      <tr>
        <td style="font-family: 'Google Sans', 'Plus Jakarta Sans', Arial, sans-serif; font-size: 15px; line-height: 24px; color: #4F5A68;">
          The Knotnex backend notification system has dispatched <strong>${currentCount} of ${maxQuota}</strong> free transactional emails today (UTC).
        </td>
      </tr>
    </table>

    <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%" style="background: #FEF2F2; border: 1px solid #FECACA; border-radius: 14px; margin: 20px 0; padding: 18px 20px;">
      <tr>
        <td>
          <div style="font-family: 'Google Sans', 'Plus Jakarta Sans', Arial, sans-serif; font-size: 14px; font-weight: 700; color: #991B1B; margin-bottom: 8px;">
            Quota Capacity: ${pct}% Consumed
          </div>
          <div style="font-family: 'Google Sans', 'Plus Jakarta Sans', Arial, sans-serif; font-size: 14px; color: #7F1D1D; line-height: 22px;">
            • Dispatched today: <strong>${currentCount}</strong><br/>
            • Remaining today: <strong>${remaining}</strong><br/>
            • Reset time: 00:00 UTC
          </div>
        </td>
      </tr>
    </table>

    ${renderCallout('To prevent transactional emails (OTP, event tickets, verification alerts) from being throttled, consider upgrading to a Brevo Starter or Business plan.', 'warning')}
  `;

  return renderEmailLayout({
    preheader,
    greeting,
    title,
    badge: {
      text: 'Capacity Warning',
      bg: '#FEF2F2',
      color: '#991B1B',
    },
    contentHtml,
    cta: {
      text: 'Brevo Dashboard',
      url: 'https://app.brevo.com/',
    },
    secondaryNotice: 'This is an automated operational alert generated by Knotnex backend quota monitoring.',
  });
}

